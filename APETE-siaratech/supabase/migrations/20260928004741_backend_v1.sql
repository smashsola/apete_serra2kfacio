create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at=now();
  return new;
end $$;

create trigger profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
create trigger stores_touch before update on public.stores for each row execute function public.touch_updated_at();
create trigger products_touch before update on public.products for each row execute function public.touch_updated_at();
create trigger orders_touch before update on public.orders for each row execute function public.touch_updated_at();
create trigger delivery_touch before update on public.delivery_assignments for each row execute function public.touch_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  insert into public.profiles(id,full_name,phone)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),coalesce(new.raw_user_meta_data->>'phone',''))
  on conflict(id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin(uid uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles p where p.id=uid and p.role='admin') $$;

create or replace function public.is_store_member(target_store uuid, uid uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.store_members sm where sm.store_id=target_store and sm.user_id=uid) $$;

create or replace function public.can_access_order(target_order uuid, uid uuid default auth.uid())
returns boolean
language sql stable security definer set search_path=public
as $$
select exists(
  select 1
  from public.orders o
  where o.id=target_order
    and (
      o.customer_id=uid
      or public.is_store_member(o.store_id,uid)
      or public.is_admin(uid)
      or exists(select 1 from public.delivery_assignments d where d.order_id=o.id and d.courier_id=uid)
    )
) $$;

grant execute on function public.is_admin(uuid) to authenticated;
grant execute on function public.is_store_member(uuid,uuid) to authenticated;
grant execute on function public.can_access_order(uuid,uuid) to authenticated;

create or replace function public.valid_order_transition(old_status public.apete_order_status,new_status public.apete_order_status)
returns boolean language sql immutable as $$
select case old_status
 when 'pending' then new_status in ('accepted','cancelled')
 when 'accepted' then new_status in ('preparing','cancelled')
 when 'preparing' then new_status in ('ready','cancelled')
 when 'ready' then new_status in ('out_for_delivery','delivered','cancelled')
 when 'out_for_delivery' then new_status in ('delivered','cancelled')
 else false end
$$;

create or replace function public.enforce_order_status_transition()
returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status and not public.valid_order_transition(old.status,new.status) then
    raise exception 'invalid_order_status_transition' using errcode='22023';
  end if;
  return new;
end $$;

create trigger orders_status_transition
before update of status on public.orders
for each row execute function public.enforce_order_status_transition();

