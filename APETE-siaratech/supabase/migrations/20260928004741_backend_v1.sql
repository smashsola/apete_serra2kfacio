-- APETÊ backend v1
-- Auth + catálogo + pedidos + comerciante + entregas.
create extension if not exists pgcrypto;

create type public.apete_profile_role as enum ('customer','merchant','courier','admin');
create type public.apete_store_member_role as enum ('owner','manager','staff');
create type public.apete_order_status as enum ('pending','accepted','preparing','ready','out_for_delivery','delivered','cancelled');
create type public.apete_delivery_status as enum ('assigned','picked_up','delivered','cancelled');
create type public.apete_merchant_application_status as enum ('pending','approved','rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.apete_profile_role not null default 'customer',
  full_name text not null default '',
  phone text not null default '',
  address text not null default '',
  neighborhood text not null default '',
  city text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.stores (
  id uuid primary key default gen_random_uuid(),
  public_id bigint generated by default as identity unique not null,
  name text not null check (char_length(name) between 2 and 100),
  category text not null default '',
  city text not null,
  description text not null default '',
  hero text not null default '',
  delivery_fee integer not null default 0 check (delivery_fee >= 0),
  producer boolean not null default false,
  delivery boolean not null default true,
  pickup boolean not null default true,
  service_areas text[] not null default '{}',
  cover text not null default '',
  verified boolean not null default false,
  active boolean not null default true,
  demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.store_members (
  store_id uuid not null references public.stores(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role public.apete_store_member_role not null default 'staff',
  created_at timestamptz not null default now(),
  primary key (store_id,user_id)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  public_id bigint generated by default as identity unique not null,
  store_id uuid not null references public.stores(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  description text not null default '',
  category text not null default '',
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  image text not null default '',
  old_price integer not null default 0 check (old_price >= 0),
  last_batch boolean not null default false,
  preferences text[] not null default '{}',
  serves integer check (serves is null or serves > 0),
  active boolean not null default true,
  demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  public_number bigint generated always as identity unique not null,
  customer_id uuid not null references public.profiles(id) on delete restrict,
  store_id uuid not null references public.stores(id) on delete restrict,
  status public.apete_order_status not null default 'pending',
  mode text not null check (mode in ('delivery','pickup')),
  city text not null,
  customer_name text not null,
  customer_phone text not null,
  address text not null default '',
  neighborhood text not null default '',
  note text not null default '',
  payment_method text not null check (payment_method in ('pix','card','card_on_delivery')),
  subtotal integer not null check (subtotal >= 0),
  delivery_fee integer not null check (delivery_fee >= 0),
  total integer not null check (total >= 0 and total = subtotal + delivery_fee),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price integer not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99),
  line_subtotal integer not null check (line_subtotal >= 0 and line_subtotal = unit_price * quantity),
  created_at timestamptz not null default now()
);

create table public.delivery_assignments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders(id) on delete cascade,
  courier_id uuid not null references public.profiles(id) on delete restrict,
  status public.apete_delivery_status not null default 'assigned',
  assigned_at timestamptz not null default now(),
  picked_up_at timestamptz,
  delivered_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.merchant_applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  store_name text not null,
  phone text not null,
  city text not null,
  document text not null,
  instagram text not null,
  status public.apete_merchant_application_status not null default 'pending',
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index orders_customer_idx on public.orders(customer_id,created_at desc);
